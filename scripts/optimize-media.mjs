// Turns the original photos in MEDIA_SRC (default ../assets) into responsive
// AVIF + WebP files in public/media and writes content/media.generated.ts
// (dimensions + tiny blur placeholders). Re-run after adding or replacing a photo:
//   npm run media
import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const SRC = path.resolve(process.env.MEDIA_SRC ?? "../assets");
const OUT = path.resolve("public/media");
const MANIFEST = path.resolve("content/media.generated.ts");

// key -> source file, output widths, optional crop (aspect w/h + gravity), optional blur
const jobs = {
  office: { file: "office-idaho-falls.jpg", widths: [640, 1080, 1600, 2200] },
  lobby: { file: "lobby-idaho-falls.jpg", widths: [640, 1080, 1600] },
  trainingSession: { file: "training-in-session-idaho-falls.jpg", widths: [640, 1080, 1600, 2200] },
  // 9:16 mobile crop of the packed Learning Center (presenter + screen side)
  trainingSessionTall: { file: "training-in-session-idaho-falls.jpg", widths: [480, 640, 828], crop: { aspect: 9 / 16, gravity: "centre" } },
  trainingRoom: { file: "training-room-idaho-falls.jpg", widths: [640, 1080, 1600] },
  trainingFinancial: { file: "training-financial-idaho-falls.jpg", widths: [480, 1024] },
  marketPulse: { file: "market-pulse-stats-idaho-falls.jpg", widths: [480, 1024] },
  mastermind: { file: "mastermind-idaho-falls-crop.jpg", widths: [480, 899] },
  // Name labels on the Zoom grid are unreadable until each person OKs it (see launch checklist)
  zoom: { file: "zoom-training.jpg", widths: [640, 1280], blur: 4 },
  redDayPoster: { file: "red-day-2026-poster.jpg", widths: [540] },
  skilledPoster: { file: "skilled-agents-win-poster.jpg", widths: [360, 720] },
};

// Open Graph images (1200x630 JPEG, what social networks expect)
const og = {
  "og-default": { file: "office-idaho-falls.jpg", gravity: "centre" },
  "og-training": { file: "training-in-session-idaho-falls.jpg", gravity: "centre" },
  "og-lobby": { file: "lobby-idaho-falls.jpg", gravity: "centre" },
};

await fs.mkdir(OUT, { recursive: true });
const manifest = {};

for (const [key, job] of Object.entries(jobs)) {
  const src = path.join(SRC, job.file);
  let base = sharp(src).rotate();
  const meta = await base.metadata();
  let w = meta.width, h = meta.height;
  if (job.crop) {
    const cw = Math.round(h * job.crop.aspect);
    base = base.extract({ left: Math.round((w - cw) / 2), top: 0, width: cw, height: h });
    w = cw;
  }
  const buf = await base.toBuffer();
  const widths = job.widths.filter((x) => x <= w);
  for (const width of widths) {
    let img = sharp(buf).resize({ width });
    if (job.blur) img = img.blur(job.blur);
    await img.clone().avif({ quality: 42 }).toFile(path.join(OUT, `${key}-${width}.avif`));
    await img.clone().webp({ quality: 72 }).toFile(path.join(OUT, `${key}-${width}.webp`));
  }
  const tiny = await sharp(buf).resize({ width: 16 }).blur(job.blur ? 2 : 0.5).webp({ quality: 40 }).toBuffer();
  manifest[key] = {
    width: widths.at(-1),
    height: Math.round((h / w) * widths.at(-1)),
    widths,
    blur: `data:image/webp;base64,${tiny.toString("base64")}`,
  };
  console.log("✓", key, widths.join(","));
}

for (const [key, job] of Object.entries(og)) {
  await sharp(path.join(SRC, job.file)).rotate().resize(1200, 630, { fit: "cover", position: job.gravity }).jpeg({ quality: 80 }).toFile(path.join(OUT, `${key}.jpg`));
  console.log("✓", key);
}

await fs.writeFile(
  MANIFEST,
  `// Generated by scripts/optimize-media.mjs. Do not edit by hand.\nexport const media = ${JSON.stringify(manifest, null, 2)} as const;\nexport type MediaKey = keyof typeof media;\n`,
);
